#!/usr/bin/env python3
"""G2 长动作测试程序；由现场人员通过网页执行或单步调试。"""

import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from runtime2 import G2


with G2() as 机器人:
    机器人.语音输出("动作开始")

    机器人.夹爪(左夹爪=1.0, 右夹爪=1.0)
    机器人.夹爪(左夹爪=0.0, 右夹爪=0.0)

    机器人.末端偏移量(
        左偏移量={"position": [0.0, 0.0, 0.05], "rotation": [0.0, 0.0, 0.0]},
    )

    机器人.夹爪(左夹爪=1.0)
    机器人.夹爪(左夹爪=0.0)

    机器人.底盘相对运动(前后=100, 左右=0, 转角=0)

    机器人.夹爪(右夹爪=1.0)
    机器人.夹爪(右夹爪=0.0)

    机器人.底盘相对运动(前后=-100, 左右=0, 转角=0)

    机器人.单关节相对运动(
        关节名称="idx11_head_joint1",
        递增量=math.radians(5),
        角速度=0.1,
    )

    机器人.底盘相对运动(前后=0, 左右=0, 转角=-5)

    机器人.单关节相对运动(
        关节名称="idx11_head_joint1",
        递增量=math.radians(-5),
        角速度=0.1,
    )

    机器人.底盘相对运动(前后=0, 左右=0, 转角=5)
