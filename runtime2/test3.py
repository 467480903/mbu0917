
from runtime2 import G2

with G2() as 机器人:

    机器人.底盘到点运动不等待("P1")
    机器人.全身关节运动("A1", 角速度=0.1)
    机器人.左手关节运动("JL1", 角速度=0.1)

    机器人.末端偏移量(
        右偏移量={
            "position": [0.0, 0.0, 0.05],
            "rotation": [0.0, 0.0, 0.0],
        }
    )

    机器人.等待底盘运动结束(timeout=180)                                             