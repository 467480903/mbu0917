
#!/usr/bin/env python3
"""使用数据库变量完成关节、末端坐标与地图点位运动的示例程序。"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from runtime2 import G2


with G2() as 机器人:
    机器人.语音输出("你好你好")

    # 关节运动，角速度单位 rad/s
    机器人.全身关节运动("A1", 角速度=0.10)
    机器人.左手关节运动("JL1", 角速度=0.10)
    机器人.右手关节运动("JR1", 角速度=0.10)
    机器人.单关节变量运动("S1", 角速度=0.10)

    # 末端坐标姿态运动
    机器人.左手坐标姿态运动("L1")
    机器人.左手坐标姿态运动("L2")
    机器人.右手坐标姿态运动("R1")

    # 底盘地图点位运动
    机器人.底盘地图点运动("P1")
    机器人.底盘地图点运动("P2")
